#!/usr/bin/env python3
"""Bake an original periodic, forced linear shallow-water field for Rainfall.

eta_t = -H div(v) + rain, v_t = -g grad(eta) - drag*v.
Staggered C-grid, symplectic time stepping, reflecting square boundary and an
absorbing outer sponge outside the visible circular pool. No runtime PDE solve.
Reference equations: https://www.cs.cornell.edu/courses/cs5220/2024fa/hw/proj3.html
Only the linear equations/grid idea is referenced; implementation/assets are ours.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/skins/rainfall'
N, FRAMES, FPS, PERIOD, SUBSTEPS = 128, 48, 16, 3.0, 10
G, DEPTH, DOMAIN = 9.81, 0.025, 2.6
DX, DT = DOMAIN / N, 1.0 / (FPS * SUBSTEPS)
STEPS = FRAMES * SUBSTEPS
GUTTER, COLS, ROWS = 2, 12, 4
SLOPE_SCALE, HEIGHT_SCALE = 0.12, 0.006


def bake():
    OUT.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(71007)
    axis = (np.arange(N) + .5) * DX - DOMAIN / 2
    x, z = np.meshgrid(axis, axis)
    radius = np.sqrt(x*x + z*z)
    sponge = np.exp(-DT * (0.08 + 7.0 * np.clip((radius-.98)/.28, 0, 1)**2))
    velocity_drag = np.exp(-1.35 * DT)
    drops = []
    forcing = {}
    for i in range(48):
        angle = i * 2.39996323 + rng.uniform(-.22, .22)
        r = .87 * np.sqrt((i+.5)/48)
        px, pz = r*np.cos(angle), r*np.sin(angle)
        step = int((i*137 + 37) % STEPS)
        sigma = rng.uniform(.024, .034)
        rr = ((x-px)**2 + (z-pz)**2) / (2*sigma*sigma)
        impulse = (1-rr) * np.exp(-rr) * rng.uniform(.0014, .0022)
        impulse -= impulse.mean()
        forcing.setdefault(step, []).append(impulse.astype(np.float64))
        drops.append([round(px, 7), round(pz, 7), step*DT, round(float(rng.uniform(.8, 1.2)), 5)])
    h = np.zeros((N, N), dtype=np.float64)
    u = np.zeros((N, N+1), dtype=np.float64)
    v = np.zeros((N+1, N), dtype=np.float64)
    def advance(step):
        for impulse in forcing.get(step, []):
            h[:] += impulse
        u[:, 1:-1] -= DT * G * (h[:, 1:] - h[:, :-1]) / DX
        v[1:-1, :] -= DT * G * (h[1:, :] - h[:-1, :]) / DX
        u[:] *= velocity_drag
        v[:] *= velocity_drag
        h[:] -= DT * DEPTH * ((u[:, 1:]-u[:, :-1])+(v[1:, :]-v[:-1, :])) / DX
        h[:] *= sponge
    residuals = []
    for cycle in range(24):
        initial = h.copy()
        for step in range(STEPS):
            advance(step)
        residuals.append(float(np.max(np.abs(h-initial))))
        if cycle >= 7 and residuals[-1] < 2e-8:
            break
    initial = h.copy()
    frames = []
    for step in range(STEPS):
        # Frame zero is the state just before that phase's scheduled impact.
        if step % SUBSTEPS == 0:
            frames.append(h.copy())
        advance(step)
    height = np.stack(frames)
    seam = float(np.max(np.abs(h-initial)))
    sz, sx = np.gradient(height, DX, axis=(1, 2))
    lap = (np.roll(height,1,1)+np.roll(height,-1,1)+np.roll(height,1,2)+np.roll(height,-1,2)-4*height)/(DX*DX)
    channels = np.stack([sx/SLOPE_SCALE*.5+.5, sz/SLOPE_SCALE*.5+.5,
                         height/HEIGHT_SCALE*.5+.5, np.clip(-lap*.18,0,1)], axis=-1)
    encoded = np.rint(np.clip(channels, 0, 1)*255).astype(np.uint8)
    stride = N + 2*GUTTER
    atlas = np.zeros((ROWS*stride, COLS*stride, 4), dtype=np.uint8)
    for i, frame in enumerate(encoded):
        padded = np.pad(frame, ((GUTTER,GUTTER),(GUTTER,GUTTER),(0,0)), mode='edge')
        atlas[(i//COLS)*stride:(i//COLS+1)*stride,(i%COLS)*stride:(i%COLS+1)*stride] = padded
    image_path = OUT / 'shallow_water_atlas.png'
    Image.fromarray(atlas).save(image_path, optimize=True)
    gd = ['extends RefCounted', '## Generated by tools/bake_rainfall_water.py. Do not hand edit.',
          'const PERIOD:=3.0', 'const FRAMES:=48', 'const DROP_DATA:Array[Vector4]=[']
    gd.extend('\tVector4('+','.join(str(c) for c in d)+'),' for d in drops)
    gd.append(']')
    (ROOT/'fidelity/rainfall_bake.gd').write_text('\n'.join(gd)+'\n')
    adjacent = np.max(np.abs(height-np.roll(height,1,0)),axis=(1,2))
    report = {'method':'Damped linear shallow-water PDE on staggered C-grid; periodic rain forcing; settled periodic state',
              'grid':[N,N], 'period_seconds':PERIOD,'frames':FRAMES,'fps':FPS,'dt':DT,'depth':DEPTH,
              'wave_speed':float(np.sqrt(G*DEPTH)), 'courant_2d':float(np.sqrt(2*G*DEPTH)*DT/DX),
              'warmup_cycles':len(residuals),'cycle_residuals':residuals,'period_seam_max_height_error':seam,
              'max_height':float(np.max(np.abs(height))), 'max_slope':float(max(np.max(np.abs(sx)),np.max(np.abs(sz)))),
              'last_to_first_frame_delta':float(adjacent[0]),'max_ordinary_frame_delta':float(adjacent[1:].max()),
              'atlas_size':[int(atlas.shape[1]),int(atlas.shape[0])],'rgba8_gpu_bytes':int(atlas.nbytes),
              'atlas_png_bytes':image_path.stat().st_size,'atlas_sha256':hashlib.sha256(image_path.read_bytes()).hexdigest(),
              'drops':drops,'source':'https://www.cs.cornell.edu/courses/cs5220/2024fa/hw/proj3.html',
              'limits':'Linear small-amplitude water, not nonlinear CFD. Normal strength is amplified artistically at runtime.'}
    assert np.isfinite(height).all() and report['courant_2d'] < .9
    assert seam < 1e-7 and report['max_height'] < DEPTH*.25
    assert report['max_slope'] < SLOPE_SCALE
    (OUT/'bake-manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({k:v for k,v in report.items() if k not in ['drops','cycle_residuals']}))


if __name__ == '__main__':
    bake()
